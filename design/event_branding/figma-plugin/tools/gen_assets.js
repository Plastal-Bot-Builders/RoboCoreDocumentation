// Writes src/00_assets_gen.js: the vector artwork the builder embeds (logos, QR code, Copperbelt contours, icons,
// the Geared Ring). Raster artwork (robot render, line drawings) is served by test/server.py instead.
//   node tools/gen_assets.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');            // RoboCore_Event_Branding
const ide = path.join(root, '..', 'RoboCore_IDE_Design', 'figma-plugin', 'src');
const A = (f) => fs.readFileSync(path.join(root, 'assets', f), 'utf8');

// RoboCore lockup (wordmark + "Zambia" between two rules), from the box artwork
const rc = A('robocore_logo.svg');
const paths = [...rc.matchAll(/<path d="([^"]+)" fill="([^"]+)"\/>/g)].map(m => ({ d: m[1], fill: m[2] }));
const lines = [...rc.matchAll(/<line x1="([\d.]+)" y1="([\d.]+)" x2="([\d.]+)" y2="([\d.]+)"[^>]*stroke-width="([\d.]+)"/g)].map(m => m.slice(1, 6).map(Number));
const black = paths.filter(p => p.fill === 'black');
// topographic lines: real Copperbelt terrain from ../topo/copperbelt_contours.py (1080 x 1080, plain and index contours)
const topo = A('contours_copperbelt.svg');
const topoGroup = (id) => [...(topo.match(new RegExp('<g id="' + id + '"[^>]*>([\\s\\S]*?)</g>')) || ['', ''])[1].matchAll(/d="([^"]+)"/g)].map(m => m[1]);
const CONTOURS = topoGroup('contours'), CONTOURS_INDEX = topoGroup('index');
const CONTOUR_SOURCE = (topo.match(/<!-- (.*?) -->/) || ['', ''])[1];
if (!CONTOURS.length) throw new Error('contours_copperbelt.svg has no contour paths');

const ROBOCORE = {
  viewBox: [0, 0, 2897, 943], word: [70, 100, 2815, 490],
  letters: black[0].d, zambia: black[1].d,
  gearOuter: paths.find(p => p.fill === '#78A3AD').d, gearInner: paths.find(p => p.fill === '#64878E').d,
  lines,                                                    // [x1, y1, x2, y2, width]
};
// Plastal-Bot Builders logo (robot head + name): black = ink, white = knockout
const PLASTAL = A('plastal_logo.svg').replace(/\n/g, '');
let QR = A('qr_website.svg');
if (!/viewBox=/.test(QR)) { const m = QR.match(/width="(\d+)" height="(\d+)"/); QR = QR.replace('<svg ', '<svg viewBox="0 0 ' + m[1] + ' ' + m[2] + '" '); }

const evalConst = (file, name, pre = '') => new Function(pre + fs.readFileSync(path.join(ide, file), 'utf8') + '\nreturn ' + name + ';')();
const ICON_ALL = evalConst('03_icons.js', 'ICON_SVG', 'const figma = {}; ');
const want = ['bot', 'blocks', 'code', 'cpu', 'wifi', 'usb', 'radio', 'gauge', 'lightbulb', 'zap', 'sparkles', 'play', 'globe', 'graduation', 'repeat', 'activity', 'thermometer', 'book-open',
  'check-circle', 'settings', 'star', 'grid', 'download', 'user'];
const ICONS = {}; for (const k of want) if (ICON_ALL[k]) ICONS[k] = ICON_ALL[k];
const APP_MARK = evalConst('00_app_mark.js', 'APP_MARK');

// pixel sizes of the raster artwork (PNG IHDR), so the builder can keep aspect ratios
const IMG_SIZE = {};
for (const dir of ['', 'renders/']) {
  const full = path.join(root, 'assets', dir);
  if (!fs.existsSync(full)) continue;
  for (const f of fs.readdirSync(full)) {
    if (!f.endsWith('.png') || f.endsWith('_5k.png')) continue;
    const b = fs.readFileSync(path.join(full, f)).subarray(16, 24);
    IMG_SIZE[dir + f] = [b.readUInt32BE(0), b.readUInt32BE(4)];
  }
}
const out = '// Generated by tools/gen_assets.js from ../assets and the IDE design builder. Do not edit by hand.\n' +
  'const ROBOCORE = ' + JSON.stringify(ROBOCORE) + ';\n' +
  'const PLASTAL_SVG = ' + JSON.stringify(PLASTAL) + ';\n' +
  'const QR_SVG = ' + JSON.stringify(QR) + ';\n' +
  'const CONTOURS = ' + JSON.stringify(CONTOURS) + ';\n' +
  'const CONTOURS_INDEX = ' + JSON.stringify(CONTOURS_INDEX) + ';\n' +
  'const CONTOUR_SOURCE = ' + JSON.stringify(CONTOUR_SOURCE) + ';\n' +
  'const ICONS = ' + JSON.stringify(ICONS) + ';\n' +
  'const APP_MARK = ' + JSON.stringify(APP_MARK) + ';\n' +
  'const IMG_SIZE = ' + JSON.stringify(IMG_SIZE) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', '00_assets_gen.js'), out);
console.log('00_assets_gen.js', out.length, 'bytes; images', Object.keys(IMG_SIZE).length);
