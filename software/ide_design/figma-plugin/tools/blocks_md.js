// Writes docs/block-catalogue.md from src/05a_block_data.js (the same data as the block library in Figma).
//   node tools/blocks_md.js
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'src', '05a_block_data.js'), 'utf8');
const prelude = "const D = (v) => ({ t: 'drop', v }), N = (v) => ({ t: 'num', v }), T = (v) => ({ t: 'text', v });\n";
const { BLOCK_CATS, BLOCK_LIBRARY, blockCatalogueRows } = new Function(prelude + src + '\nreturn { BLOCK_CATS, BLOCK_LIBRARY, blockCatalogueRows };')();
const esc = (s) => String(s).replace(/\|/g, '\\|');
const table = (head, rows) => ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|', ...rows.map(r => '| ' + r.map(esc).join(' | ') + ' |')].join('\n');
const rows = blockCatalogueRows();
const toAdd = rows.filter(r => r[4] !== 'exists').length;
const out = [];
out.push('# RoboCore IDE — block catalogue', '');
out.push('The Blocks editor’s block set: hardware-first blocks for the RoboCore V2, in the spirit of LEGO SPIKE Prime’s word blocks (the ideas, not their art). Blocks name what the robot does; each action has a “for …”, a “start …” and a “stop” form; each sensor has a value, a yes / no question and a “when …” hat.', '');
out.push(`${BLOCK_LIBRARY.length} blocks in ${BLOCK_CATS.length} categories; ${toAdd} need a new helper in the RoboCore library (firmware/RoboCore). Generated from \`figma-plugin/src/05a_block_data.js\` by \`node tools/blocks_md.js\`; do not edit this file by hand. In Figma: page 02 (Blocks family), page 01 (Blocks), page 07 (Block catalogue).`, '');
out.push('Notation: [dropdown] (number) “text” < > empty yes / no slot.', '');
out.push('## Categories', '', table(['Category', 'Colour token', 'What it is for'], BLOCK_CATS.map(([c, , k, d]) => [c, '`color/block/' + k + '`', d])), '');
for (const [cat] of BLOCK_CATS) {
  out.push('## ' + cat, '', table(['Block', 'Shape', 'Generates (C++)', 'RoboCore library'], rows.filter(r => r[0] === cat).map(r => [r[1], r[2], '`' + r[3] + '`', r[4]])), '');
}
fs.writeFileSync(path.join(__dirname, '..', '..', 'docs', 'block-catalogue.md'), out.join('\n') + '\n');
console.log('docs/block-catalogue.md: ' + BLOCK_LIBRARY.length + ' blocks, ' + toAdd + ' need library work');
