// Writes docs/behaviour-spec.md from src/10d_spec_data.js (the same data as page 07 in Figma).
//   node tools/spec_md.js
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'src', '10d_spec_data.js'), 'utf8');
const { SPEC, HANDOFF, PROTO_LIMITS } = new Function(src + '\nreturn { SPEC, HANDOFF, PROTO_LIMITS };')();
const esc = (s) => String(s).replace(/\|/g, '\\|');
const table = (head, rows) => ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|', ...rows.map(r => '| ' + r.map(esc).join(' | ') + ' |')].join('\n');
const total = SPEC.reduce((a, s) => a + s.rows.length, 0);
const out = [];
out.push('# RoboCore IDE — behaviour spec and test checklist', '');
out.push('Every control in the RoboCore IDE, what it must do, and where to try it in the Figma prototype ([RoboCore IDE — UI/UX Design](https://www.figma.com/design/P7i2WBM8G96B2fTPHpp8yi), page 05). Blocks are Google Blockly; the code editor is Monaco.', '');
out.push('Each row is one test case. Run it in the prototype now, and on the built app later. IDs are stable: add new rows at the end of an area.', '');
out.push(`${total} test cases in ${SPEC.length} areas. Generated from \`figma-plugin/src/10d_spec_data.js\` by \`node tools/spec_md.js\`; do not edit this file by hand.`, '');
out.push('## Contents', '', ...SPEC.map(s => `- [${s.id} — ${s.area}](#${(s.id + '--' + s.area).toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')})`), '- [Handoff: Blockly](#handoff-blockly)', '- [Handoff: Monaco](#handoff-monaco)', '- [Implementation notes](#implementation-notes)', '- [What the prototype cannot do](#what-the-prototype-cannot-do)', '');
for (const s of SPEC) {
  out.push(`## ${s.id} — ${s.area}`, '');
  out.push(table(['ID', 'Control', 'Do', 'Expect', 'Prototype', 'Pass'], s.rows.map((r, i) => [s.id + '-' + String(i + 1).padStart(2, '0'), r[0], r[1], r[2], '`' + r[3] + '`', '☐'])), '');
}
out.push('## Handoff: Blockly', '', table(['Setting', 'Value', 'Note'], HANDOFF.blocklyTheme.map(r => [r[0], '`' + r[1] + '`', r[2]])), '');
out.push('## Handoff: Monaco', '', table(['Setting', 'Value', 'Note'], HANDOFF.monaco.map(r => [r[0], '`' + r[1] + '`', r[2]])), '');
out.push('## Implementation notes', '', table(['Topic', 'Note'], HANDOFF.notes), '');
out.push('## What the prototype cannot do', '', table(['Limit', 'Why and what to do'], PROTO_LIMITS), '');
fs.writeFileSync(path.join(__dirname, '..', '..', 'docs', 'behaviour-spec.md'), out.join('\n') + '\n');
console.log('docs/behaviour-spec.md: ' + total + ' test cases');
